<?php
/**
 * What a fresh server starts with (categories, the four bank cards + cash),
 * for the app without a server: php tools/local-app/seed.php > server/app/local/seed.js
 */
$tmp = sys_get_temp_dir() . '/ba-seed-' . getmypid();
@mkdir($tmp);
$GLOBALS['__ba_seed_dir'] = $tmp;
$src = __DIR__ . '/../../server';
copy("$src/lib.php", "$tmp/lib.php");
foreach (glob("$src/*.php") as $f) if (!is_file("$tmp/" . basename($f))) copy($f, "$tmp/" . basename($f));
@mkdir("$tmp/data");
file_put_contents("$tmp/config.php", "<?php return ['app_token' => 'x', 'device_token' => 'y', 'timezone' => 'Asia/Tehran'];");
require "$tmp/lib.php";
$db = ba_db();
$cats = $db->query('SELECT id, name, direction, keywords, sort_order, kind FROM categories ORDER BY sort_order, id')->fetchAll(PDO::FETCH_ASSOC);
$wal = $db->query('SELECT id, name, kind, opening, is_sms, bank, card, color FROM wallets ORDER BY id')->fetchAll(PDO::FETCH_ASSOC);
foreach ($cats as &$c) { $c['id'] = (int)$c['id']; $c['sort_order'] = (int)$c['sort_order']; }
foreach ($wal as &$w) { $w['id'] = (int)$w['id']; $w['opening'] = (int)$w['opening']; $w['is_sms'] = (int)$w['is_sms']; }
echo "/* generated by tools/local-app/seed.php from a fresh server: do not edit */\n";
echo 'window.BA_SEED = ' . json_encode(['categories' => $cats, 'wallets' => $wal], JSON_UNESCAPED_UNICODE) . ";\n";
exec('rm -rf ' . escapeshellarg($tmp));
